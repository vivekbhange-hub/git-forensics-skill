#!/usr/bin/env python3
"""coupling: find files that change together (temporal coupling) from git history alone.

Over the commits in the window it counts how often each pair of files is changed in the same commit.
For a pair A, B it reports shared commits, support (shared / all commits considered) and confidence
in both directions: confidence A->B is the share of A's commits that also touched B. It flags pairs
that live in different top-level directories (cross-module coupling), pairs where one file is a test
of the other (expected coupling), and pairs where neither file mentions the other's name (no visible
reference, a candidate hidden dependency).

  coupling.py path/to/repo --since "12 months ago" --min-shared 4 --min-confidence 0.6
  coupling.py . --hidden-only --top 10 --json

Commits that touch more than --max-files files are skipped as bulk edits (reformats, renames, vendor
drops). Streams `git log --numstat -M -z`; memory grows with the number of distinct pairs and is
pruned past --max-pairs (counts for rare pairs may then be low, and the report says so).
Exit codes: 0 ok, 1 --fail-above pairs found, 2 usage or input error. Standard library and git only.
"""
from __future__ import annotations

import argparse
import json
