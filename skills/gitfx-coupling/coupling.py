TEST_PARTS = {"test", "tests", "spec", "specs", "__tests__", "e2e"}


def is_test_path(path):
    parts = path.lower().split("/")
    name = parts[-1]
    stem = name.rsplit(".", 1)[0]
    if any(p in TEST_PARTS for p in parts[:-1]):
        return True
    return stem.startswith("test_") or stem.endswith("_test") or stem.endswith(".test") or stem.endswith(".spec")


def is_test_pair(a, b, linked):
    """One file is a test and it either carries the other file's name or mentions it."""
    if is_test_path(a) == is_test_path(b):
        return False
    test, code = (a, b) if is_test_path(a) else (b, a)
    name = re.sub(r"^test_|_test$|\.test$|\.spec$", "", stem_of(test))
    return name.lower() == stem_of(code).lower() or bool(linked)


def stem_of(path):
    name = path.rsplit("/", 1)[-1]
    return name.split(".", 1)[0] if not name.startswith(".") else name


class Counter(object):
    """Pair and file counts over the accepted commits."""

    def __init__(self, min_shared, max_pairs):
        self.files = {}
        self.pairs = {}
        self.commits = 0
        self.skipped_bulk = 0
        self.skipped_single = 0
        self.min_shared = min_shared
        self.max_pairs = max_pairs
        self.pruned = False

    def add(self, paths):
        self.commits += 1
        for path in paths:
            self.files[path] = self.files.get(path, 0) + 1
        ordered = sorted(paths)
        for i in range(len(ordered)):
            for j in range(i + 1, len(ordered)):
                key = (ordered[i], ordered[j])
                self.pairs[key] = self.pairs.get(key, 0) + 1
        if len(self.pairs) > self.max_pairs and self.min_shared >= 2:
            self.pairs = dict((k, v) for k, v in self.pairs.items() if v > 1)
            self.pruned = True


def collect(repo, since, until, pathspecs, patterns, max_files, min_shared, max_pairs):
    current = tracked_files(repo)
    counter = Counter(min_shared, max_pairs)
    renames = RenameMap()
    for commit in iter_commits(repo, since, until, pathspecs):
        raw_count = len(commit.changes)
        paths = set()
        for change in commit.changes:
            renames.note(change)
            if is_pure_rename(change) or change.binary:
                continue
            path = renames.resolve(change.path)
            if path in current and not is_excluded(path, patterns):
                paths.add(path)
        if raw_count > max_files:
            counter.skipped_bulk += 1
            continue
        if len(paths) < 2:
            counter.skipped_single += 1
            # still counts toward each file's own commit total, so confidence stays honest
            for path in paths:
                counter.files[path] = counter.files.get(path, 0) + 1
            counter.commits += 1
            continue
        counter.add(paths)
    return counter


class RefChecker(object):
    """Cheap reference check: does the file name stem of one file appear in the other file?"""

    def __init__(self, repo):
        self.repo = repo
        self.cache = {}

    def text(self, path):
        if path not in self.cache:
            data = read_bytes(self.repo, path)
            self.cache[path] = "" if data is None or looks_binary(data) else data.decode("utf-8", "replace")
        return self.cache[path]

    def mentions(self, source, target):
        """True/False whether `target`'s stem occurs as a word in `source`; None when the stem is too generic."""
        stem = stem_of(target)
        if len(stem) < 3 or stem in ("__init__", "index"):
            return None
        return re.search(r"(?<![A-Za-z0-9_])" + re.escape(stem) + r"(?![A-Za-z0-9_])", self.text(source)) is not None

    def linked(self, a, b):
        first, second = self.mentions(a, b), self.mentions(b, a)
        if first is None and second is None:
            return None
        return bool(first) or bool(second)


def candidate_pairs(counter, min_shared, min_confidence):
    rows = []
    for (a, b), shared in counter.pairs.items():
        if shared < min_shared:
            continue
        conf_ab = shared / float(counter.files[a])
        conf_ba = shared / float(counter.files[b])
        if max(conf_ab, conf_ba) < min_confidence:
            continue
        rows.append({
            "a": a, "b": b, "shared": shared,
            "commits_a": counter.files[a], "commits_b": counter.files[b],
            "support": round(shared / float(counter.commits), 3),
            "confidence_a_to_b": round(conf_ab, 2),
            "confidence_b_to_a": round(conf_ba, 2),
        })
    rows.sort(key=lambda r: (-r["shared"], -max(r["confidence_a_to_b"], r["confidence_b_to_a"]), r["a"], r["b"]))
    return rows


def annotate(rows, refs):
    for row in rows:
        row["cross_module"] = top_dir(row["a"]) != top_dir(row["b"])
        row["linked"] = refs.linked(row["a"], row["b"])
        row["test_pair"] = is_test_pair(row["a"], row["b"], row["linked"])
        row["hidden"] = bool(row["cross_module"] and not row["test_pair"] and row["linked"] is False)
    return rows


def clusters(rows):
    """Connected groups of files joined by the reported pairs (union-find), largest first."""
    parent = {}

    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for row in rows:
        parent[find(row["a"])] = find(row["b"])
    groups = {}
    for name in list(parent):
        groups.setdefault(find(name), []).append(name)
    result = [sorted(g) for g in groups.values() if len(g) >= 2]
    result.sort(key=lambda g: (-len(g), g[0]))
    return result


def render_markdown(report):
    out = ["# Temporal coupling: " + report["repo"], ""]
    window = report["window"]
    span = "all history" if not (window["since"] or window["until"]) else \
        "{} to {}".format(window["since"] or "start", window["until"] or "now")
    out.append("- Window: " + span)
    out.append("- Commits counted: {} ({} touched only one tracked file); skipped {} bulk commits touching "
               "more than {} files".format(report["commits_considered"], report["skipped_single_file_commits"],
                                           report["skipped_bulk_commits"], report["max_files"]))
    out.append("- Pairs shown: shared commits >= {}, confidence >= {} in at least one direction".format(
        report["min_shared"], report["min_confidence"]))
    if report["pruned"]:
        out.append("- Note: pair counts were pruned past --max-pairs, so rare pairs may be undercounted")
    out.append("")
    out.append("| # | File A | File B | Shared | Support | A->B | B->A | Cross-module | Reference | Flags |")
    out.append("|--:|---|---|--:|--:|--:|--:|---|---|---|")
    for i, row in enumerate(report["pairs"], 1):
        ref = {True: "mentioned", False: "none seen", None: "unknown"}[row["linked"]]
        flags = []
        if row["hidden"]:
            flags.append("hidden dependency?")
        if row["test_pair"]:
            flags.append("test and code")
        out.append("| {} | `{}` | `{}` | {} | {} | {} | {} | {} | {} | {} |".format(
            i, row["a"], row["b"], row["shared"], row["support"], row["confidence_a_to_b"],
            row["confidence_b_to_a"], "yes" if row["cross_module"] else "no", ref,
            ", ".join(flags) or "-"))
    if not report["pairs"]:
        out.append("| - | no pairs met the thresholds | - | - | - | - | - | - | - | - |")
    out.append("")
    if report["clusters"]:
        out.append("## Clusters")
        out.append("")
        for i, group in enumerate(report["clusters"], 1):
            out.append("{}. {}".format(i, ", ".join("`{}`".format(f) for f in group)))
        out.append("")
    out.append("Reference means the file name (without extension) of one file appears as a word in the other. "
               "It is a cheap text check: generic names, dynamic loading and config files fool it.")
    out.append("")
    return "\n".join(out)


def parse_args(argv):
    parser = argparse.ArgumentParser(
        prog="coupling.py", description="Find files that change together, from git history.")
    parser.add_argument("repo", nargs="?", default=".", help="path inside a git repository (default .)")
    parser.add_argument("--since", help='start of the window, anything git understands ("12 months ago")')
    parser.add_argument("--until", help="end of the window")
    parser.add_argument("--path", action="append", default=[], metavar="PATHSPEC",
                        help="limit history to this path (repeatable)")
    parser.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                        help="skip files matching this glob or dir/ (repeatable, added to the defaults)")
    parser.add_argument("--no-default-excludes", action="store_true",
                        help="do not skip lockfiles, vendored, generated, minified and binary files")
    parser.add_argument("--max-files", type=int, default=30,
                        help="skip commits touching more files than this (default 30)")
    parser.add_argument("--min-shared", type=int, default=3, help="minimum shared commits (default 3)")
    parser.add_argument("--min-confidence", type=float, default=0.5,
                        help="minimum confidence in at least one direction, 0 to 1 (default 0.5)")
    parser.add_argument("--hidden-only", action="store_true",
                        help="show only cross-module pairs with no visible reference, excluding test pairs")
    parser.add_argument("--max-pairs", type=int, default=2000000,
                        help="prune rare pairs when more than this many distinct pairs are held")
    parser.add_argument("--top", type=int, default=20, help="rows to show (default 20)")
    parser.add_argument("--label", help="name to print instead of the repository folder name")
    parser.add_argument("--fail-above", type=int, metavar="N",
                        help="exit 1 if at least N pairs are flagged as hidden dependencies")
    parser.add_argument("--json", action="store_true", help="print JSON instead of markdown")
    parser.add_argument("-o", "--output", help="write the report to this file instead of stdout")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    setup_output()
    args = parse_args(argv)
    if args.top < 1 or args.max_files < 1 or args.min_shared < 1 or not 0 <= args.min_confidence <= 1:
        print("coupling: --top, --max-files and --min-shared must be at least 1 and "
              "--min-confidence between 0 and 1", file=sys.stderr)
        return 2
    try:
        repo = open_repo(args.repo)
        patterns = exclude_patterns(args.exclude, not args.no_default_excludes)
        counter = collect(repo, args.since, args.until, args.path, patterns, args.max_files,
                          args.min_shared, args.max_pairs)
        rows = candidate_pairs(counter, args.min_shared, args.min_confidence)
    except GitError as exc:
        print("coupling: " + str(exc), file=sys.stderr)
        return 2
    refs = RefChecker(repo)
    if args.hidden_only:
        shown = [r for r in annotate(rows, refs) if r["hidden"]]
    else:
        shown = annotate(rows[:args.top], refs)
    hidden_total = sum(1 for r in shown if r["hidden"])
    report = {
        "repo": args.label or os.path.basename(repo.rstrip("/\\")) or "repo",
        "window": {"since": args.since, "until": args.until},
        "commits_considered": counter.commits,
        "skipped_bulk_commits": counter.skipped_bulk,
        "skipped_single_file_commits": counter.skipped_single,
        "max_files": args.max_files,
        "min_shared": args.min_shared,
        "min_confidence": args.min_confidence,
        "pruned": counter.pruned,
        "pairs": shown[:args.top],
        "clusters": clusters(shown),
        "limits": [
            "Co-change shows what moves together, not why; squash merges glue unrelated files together.",
            "The reference check compares file name stems as text and is easily fooled.",
            "Renames are followed only when git detects them (similarity 50 percent or more).",
        ],
    }
    text = json.dumps(report, indent=2, sort_keys=True) + "\n" if args.json else render_markdown(report)
    if args.output:
        with open(args.output, "w", newline="\n", encoding="utf-8") as handle:
            handle.write(text)
    else:
        sys.stdout.write(text)
    if args.fail_above is not None and hidden_total >= args.fail_above:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
