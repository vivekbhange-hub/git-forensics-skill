#!/usr/bin/env python3
"""hotspots: rank the files that change often and are expensive to change, from git history alone.

For every file touched in the window it reports commits, lines added and deleted, distinct authors,
current size (lines, plus an indentation-depth proxy for complexity) and the share of touching
commits whose subject looks like a fix. The hotspot score multiplies two rank percentiles, churn
(commits) and complexity (lines x (1 + mean indent level)), so a big file nobody touches and a tiny
file everybody touches both score low.

  hotspots.py path/to/repo --since "12 months ago" --top 15
  hotspots.py . --path src --exclude "*.sql" --json

Streams `git log --numstat -M -z`, never loads the history into memory (only per-file counters).
Files that no longer exist, binaries, lockfiles, vendored, generated and minified files are skipped
unless you change --exclude / --no-default-excludes. Exit codes: 0 ok, 1 a score reached
--fail-above, 2 usage or input error. Standard library and git only, Python 3.9+.
"""
from __future__ import annotations

import argparse
import json
import re
import sys

