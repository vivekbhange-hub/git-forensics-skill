FIX_RE = re.compile(r"\b(fix|fixes|fixed|fixing|bug|bugs|bugfix|hotfix|revert|reverts|reverted|regression)\b",
                    re.IGNORECASE)


class FileStats(object):
    __slots__ = ("commits", "added", "deleted", "authors", "fixes", "first", "last")

    def __init__(self):
        self.commits = 0
        self.added = 0
        self.deleted = 0
        self.authors = set()
        self.fixes = 0
        self.first = None
        self.last = None


def collect(repo, since, until, pathspecs, patterns):
    """Read the log once. Returns (stats by current path, commits scanned, commits skipped as empty)."""
    stats = {}
    renames = RenameMap()
    scanned = 0
    for commit in iter_commits(repo, since, until, pathspecs):
        scanned += 1
        is_fix = bool(FIX_RE.search(commit.subject))
        seen = set()
        for change in commit.changes:
            renames.note(change)
            path = renames.resolve(change.path)
            if path in seen or is_excluded(path, patterns):
                continue
            if is_pure_rename(change) or change.binary:
                continue
            seen.add(path)
            entry = stats.get(path)
            if entry is None:
                entry = stats[path] = FileStats()
            entry.commits += 1
            entry.added += change.added
            entry.deleted += change.deleted
            entry.authors.add(commit.email)
            if is_fix:
                entry.fixes += 1
            if entry.last is None or commit.ts > entry.last:
                entry.last = commit.ts
            if entry.first is None or commit.ts < entry.first:
                entry.first = commit.ts
    return stats, scanned


def measure(data):
    """(lines, max indent level, mean indent level) for file bytes; one level is 4 columns."""
    if not data:
        return 0, 0.0, 0.0
    lines = 0
    widths = []
    for raw in data.split(b"\n"):
        lines += 1
        stripped = raw.strip()
        if not stripped:
            continue
        width = 0
        for byte in raw:
            if byte == 32:
                width += 1
            elif byte == 9:
                width += 4 - (width % 4)
            else:
                break
        widths.append(width)
    if data.endswith(b"\n"):
        lines -= 1
    if not widths:
        return lines, 0.0, 0.0
    levels = [w / 4.0 for w in widths]
    return lines, max(levels), sum(levels) / len(levels)


def percentile_ranks(values):
    """Average-rank percentile in (0, 1] for each value; ties share a rank."""
    order = sorted(range(len(values)), key=lambda i: values[i])
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
            j += 1
        average = (i + j) / 2.0 + 1.0
        for k in range(i, j + 1):
            ranks[order[k]] = average
        i = j + 1
    n = float(len(values))
    return [r / n for r in ranks]


def build_rows(repo, stats):
    current = tracked_files(repo)
    rows = []
    unreadable = 0
    for path in sorted(stats):
        if path not in current:
            continue
        data = read_bytes(repo, path)
        if data is None or looks_binary(data):
            unreadable += 1
            continue
        lines, max_indent, mean_indent = measure(data)
        if lines == 0:
            continue
        entry = stats[path]
        rows.append({
            "file": path,
            "commits": entry.commits,
            "added": entry.added,
            "deleted": entry.deleted,
            "authors": len(entry.authors),
            "lines": lines,
            "max_indent": round(max_indent, 1),
            "mean_indent": round(mean_indent, 2),
            "complexity": round(lines * (1.0 + mean_indent), 1),
            "fix_commits": entry.fixes,
            "fix_share": round(100.0 * entry.fixes / entry.commits, 1),
        })
    churn = percentile_ranks([r["commits"] for r in rows])
    size = percentile_ranks([r["complexity"] for r in rows])
    for row, c, s in zip(rows, churn, size):
        row["churn_pct"] = round(100.0 * c, 1)
        row["complexity_pct"] = round(100.0 * s, 1)
        row["score"] = round(100.0 * c * s, 1)
    rows.sort(key=lambda r: (-r["score"], -r["commits"], r["file"]))
    for rank, row in enumerate(rows, 1):
        row["rank"] = rank
    return rows, unreadable


def flag(row):
    """Short plain-language reasons a file was ranked; used in the markdown 'Why' column."""
    why = []
    if row["churn_pct"] >= 80:
        why.append("changes often")
    if row["complexity_pct"] >= 80:
        why.append("large and deeply nested" if row["mean_indent"] >= 1.5 else "large")
    if row["fix_share"] >= 40 and row["commits"] >= 3:
        why.append("many fixes")
    if row["authors"] >= 4:
        why.append("many authors")
    return ", ".join(why) if why else "-"


def render_markdown(report):
    lines = ["# Hotspots: " + report["repo"], ""]
    window = report["window"]
    span = "all history" if not (window["since"] or window["until"]) else \
        "{} to {}".format(window["since"] or "start", window["until"] or "now")
    lines.append("- Window: " + span)
    lines.append("- Commits scanned: {} (merge commits skipped)".format(report["commits_scanned"]))
    lines.append("- Files ranked: {} (existing text files touched in the window, after excludes)".format(
        report["files_ranked"]))
    if report["paths"]:
        lines.append("- Path filter: " + ", ".join(report["paths"]))
    lines.append("- Score: churn percentile x complexity percentile, 0 to 100; complexity is "
                 "lines x (1 + mean indent level)")
    lines.append("")
    lines.append("| # | File | Score | Commits | +Lines | -Lines | Authors | Lines | Max indent | Mean indent "
                 "| Fix share | Why |")
    lines.append("|--:|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|---|")
    for row in report["hotspots"]:
        lines.append("| {rank} | `{file}` | {score} | {commits} | {added} | {deleted} | {authors} | {lines} "
                     "| {max_indent} | {mean_indent} | {fix_share}% | {why} |".format(
                         why=flag(row), **row))
    if not report["hotspots"]:
        lines.append("| - | no files matched | - | - | - | - | - | - | - | - | - | - |")
    lines.append("")
    lines.append("Fix share is the percentage of a file's commits whose subject mentions fix, bug, hotfix, "
                 "revert or regression. It is a sanity check on the churn, not a measure of quality.")
    lines.append("")
    return "\n".join(lines)


def parse_args(argv):
    parser = argparse.ArgumentParser(
        prog="hotspots.py",
        description="Rank churn x complexity hotspots from git history.")
    parser.add_argument("repo", nargs="?", default=".", help="path inside a git repository (default .)")
    parser.add_argument("--since", help='start of the window, anything git understands ("12 months ago")')
    parser.add_argument("--until", help="end of the window")
    parser.add_argument("--path", action="append", default=[], metavar="PATHSPEC",
                        help="limit history to this path (repeatable, relative to the repo root)")
    parser.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                        help="skip files matching this glob or dir/ (repeatable, added to the defaults)")
    parser.add_argument("--no-default-excludes", action="store_true",
                        help="do not skip lockfiles, vendored, generated, minified and binary files")
    parser.add_argument("--top", type=int, default=20, help="rows to show (default 20)")
    parser.add_argument("--min-commits", type=int, default=1, help="ignore files with fewer commits")
    parser.add_argument("--label", help="name to print instead of the repository folder name")
    parser.add_argument("--fail-above", type=float, metavar="SCORE",
                        help="exit 1 if any file scores at or above this value (0 to 100)")
    parser.add_argument("--json", action="store_true", help="print JSON instead of markdown")
    parser.add_argument("-o", "--output", help="write the report to this file instead of stdout")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    setup_output()
    args = parse_args(argv)
    if args.top < 1:
        print("hotspots: --top must be at least 1", file=sys.stderr)
        return 2
    try:
        repo = open_repo(args.repo)
        patterns = exclude_patterns(args.exclude, not args.no_default_excludes)
        stats, scanned = collect(repo, args.since, args.until, args.path, patterns)
        rows, unreadable = build_rows(repo, stats)
    except GitError as exc:
        print("hotspots: " + str(exc), file=sys.stderr)
        return 2
    rows = [r for r in rows if r["commits"] >= args.min_commits]
    for rank, row in enumerate(rows, 1):
        row["rank"] = rank
    report = {
        "repo": args.label or os.path.basename(repo.rstrip("/\\")) or "repo",
        "window": {"since": args.since, "until": args.until},
        "paths": list(args.path),
        "commits_scanned": scanned,
        "files_ranked": len(rows),
        "skipped_unreadable_or_binary": unreadable,
        "hotspots": rows[:args.top],
        "limits": [
            "Renames are followed only when git detects them (similarity 50 percent or more).",
            "Complexity is an indentation proxy, not cyclomatic complexity.",
            "Fix share reads commit subjects; squash merges and vague subjects hide fixes.",
        ],
    }
    text = json.dumps(report, indent=2, sort_keys=True) + "\n" if args.json else render_markdown(report)
    if args.output:
        with open(args.output, "w", newline="\n", encoding="utf-8") as handle:
            handle.write(text)
    else:
        sys.stdout.write(text)
    if args.fail_above is not None and any(r["score"] >= args.fail_above for r in rows):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
