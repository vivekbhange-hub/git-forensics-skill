#!/usr/bin/env python3
"""owners: who knows this code, and what happens if they leave? Bus factor and knowledge at risk.

For the most-changed files it runs `git blame --line-porcelain` (streamed) and shares the surviving
lines out by author; for everything else, and with --fast, it shares commits. The bus factor of a
file, directory or repository is the smallest number of authors whose combined share reaches 50
percent. A file is "knowledge at risk" when its main owner holds at least --min-share of it and has
made no commit anywhere in the repository for --inactive-days (default 180).

  owners.py path/to/repo --since "24 months ago" --top 15
  owners.py . --fast --merge-email-domain corp.example.com --as-of 2026-11-01 --json

Authors are merged through .mailmap (git applies it) and --merge-email-domain (the same local part at
any listed domain is one person). Bot identities are left out unless you pass --include-bots.
This measures who committed, not who understands or who is good. Do not use it to rank people.
Exit codes: 0 ok, 1 --fail-at-risk files reached, 2 usage or input error. Standard library and git only.
"""
