BOT_PATTERNS = [r"\[bot\]", r"^dependabot", r"^renovate", r"^github-actions", r"-bot@", r"^bot@"]


class People(object):
    """Merge identities by a canonical key and remember the commonest display name."""

    def __init__(self, domains, bot_res):
        self.domains = set(d.lower().lstrip("@") for d in domains)
        self.bot_res = bot_res
        self.names = {}
        self.keys = {}

    def key(self, name, email):
        email = (email or "").strip().lower().strip("<>")
        if not email:
            key = "name:" + (name or "unknown").strip().lower()
        else:
            local, _, domain = email.partition("@")
            if domain in self.domains:
                key = re.sub(r"^\d+\+", "", local)
            else:
                key = email
        counts = self.names.setdefault(key, {})
        counts[name] = counts.get(name, 0) + 1
        self.keys[(name, email)] = key
        return key

    def display(self, key):
        counts = self.names.get(key) or {key: 1}
        return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[0][0] or key

    def is_bot(self, name, email):
        label = "{} <{}>".format(name, email)
        return any(r.search(label) for r in self.bot_res)


def bus_factor(counts):
    """Smallest number of authors whose combined share reaches 50 percent (0 when there is no data)."""
    total = float(sum(counts.values()))
    if total <= 0:
        return 0
    running = 0.0
    for i, value in enumerate(sorted(counts.values(), reverse=True), 1):
        running += value
        if running >= total * 0.5:
            return i
    return len(counts)


def top_owner(counts):
    if not counts:
        return None, 0.0
    key, value = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[0]
    return key, value / float(sum(counts.values()))


def collect(repo, since, until, pathspecs, patterns, people):
    """One pass over the log: commit counts by file, directory and repository."""
    files, dirs, repo_counts = {}, {}, {}
    renames = RenameMap()
    bot_commits = 0
    scanned = 0
    for commit in iter_commits(repo, since, until, pathspecs):
        scanned += 1
        if people.is_bot(commit.name, commit.email):
            bot_commits += 1
            for change in commit.changes:      # renames still need following
                renames.note(change)
            continue
        key = people.key(commit.name, commit.email)
        touched, folders = set(), set()
        for change in commit.changes:
            renames.note(change)
            if is_pure_rename(change) or change.binary:
                continue
            path = renames.resolve(change.path)
            if is_excluded(path, patterns):
                continue
            touched.add(path)
            folders.add(top_dir(path))
        for path in touched:
            counts = files.setdefault(path, {})
            counts[key] = counts.get(key, 0) + 1
        for folder in folders:
            counts = dirs.setdefault(folder, {})
            counts[key] = counts.get(key, 0) + 1
        if touched:
            repo_counts[key] = repo_counts.get(key, 0) + 1
    return files, dirs, repo_counts, scanned, bot_commits


def last_activity(repo, until, people):
    """Latest commit time per canonical author over the whole history (up to `until`)."""
    last = {}
    for commit in iter_commits(repo, None, until, None, numstat=False):
        if people.is_bot(commit.name, commit.email):
            continue
        key = people.key(commit.name, commit.email)
        if commit.ts > last.get(key, 0):
            last[key] = commit.ts
    return last


def blame_file(repo, path, timeout, ignore_revs, people):
    """Surviving lines per canonical author for one file, or None if blame failed or timed out."""
    args = ["blame", "--line-porcelain", "-w", "-M"]
    if ignore_revs:
        args += ["--ignore-revs-file", ignore_revs]
    args += ["HEAD", "--", path]
    errfile = tempfile.TemporaryFile()
    try:
        proc = subprocess.Popen(git_args(repo, args), stdout=subprocess.PIPE, stderr=errfile,
                                env=git_env())
    except OSError:
        errfile.close()
        return None, 0
    timer = threading.Timer(timeout, proc.kill)
    timer.start()
    counts, bot_lines = {}, 0
    name = email = ""
    try:
        for raw in proc.stdout:
            if raw.startswith(b"author "):
                name = raw[7:].rstrip(b"\r\n").decode("utf-8", "replace")
            elif raw.startswith(b"author-mail "):
                email = raw[12:].rstrip(b"\r\n").decode("utf-8", "replace").strip("<>")
            elif raw.startswith(b"\t"):
                if people.is_bot(name, email):
                    bot_lines += 1
                else:
                    key = people.key(name, email)
                    counts[key] = counts.get(key, 0) + 1
        proc.stdout.close()
        code = proc.wait()
    finally:
        timer.cancel()
        if proc.poll() is None:
            proc.kill()
            proc.wait()
        errfile.close()
    if code != 0:
        return None, 0
    return counts, bot_lines


def shares(counts, people, limit=3):
    total = float(sum(counts.values())) or 1.0
    ordered = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:limit]
    return [{"author": people.display(k), "share": round(100.0 * v / total, 1)} for k, v in ordered]


def fmt_day(ts):
    return datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%Y-%m-%d")


def analyse(repo, args, people, patterns, as_of_ts, until):
    files, dirs, repo_counts, scanned, bot_commits = collect(
        repo, args.since, until, args.path, patterns, people)
    last = last_activity(repo, until, people)
    current = tracked_files(repo)
    files = dict((p, c) for p, c in files.items() if p in current)
    # which files get the expensive blame treatment
    if args.file:
        chosen = [p for p in args.file if p in files or p in current]
    elif args.fast:
        chosen = []
    else:
        ranked = sorted(files, key=lambda p: (-sum(files[p].values()), p))
        chosen = ranked[:args.top]
    ignore_revs = args.ignore_revs
    if ignore_revs is None and os.path.exists(os.path.join(repo, ".git-blame-ignore-revs")):
        ignore_revs = ".git-blame-ignore-revs"
    blamed, timeouts, bot_lines = {}, [], 0
    for path in chosen:
        counts, bots = blame_file(repo, path, args.blame_timeout, ignore_revs, people)
        if counts is None:
            timeouts.append(path)
        else:
            blamed[path] = counts
            bot_lines += bots
    rows = []
    for path in sorted(set(files) | set(blamed)):
        commit_counts = files.get(path, {})
        counts = blamed.get(path) or commit_counts
        basis = "blame" if path in blamed else "commits"
        owner, share = top_owner(counts)
        if owner is None:
            continue
        owner_last = last.get(owner)
        rows.append({
            "file": path,
            "commits": sum(commit_counts.values()),
            "authors": len(counts),
            "bus_factor": bus_factor(counts),
            "main_owner": people.display(owner),
            "owner_share": round(100.0 * share, 1),
            "owner_last_commit": fmt_day(owner_last) if owner_last else None,
            "owner_idle_days": int((as_of_ts - owner_last) // 86400) if owner_last else None,
            "basis": basis,
            "top_authors": shares(counts, people),
        })
    rows.sort(key=lambda r: (-r["commits"], r["file"]))
    at_risk = [r for r in rows
               if r["owner_idle_days"] is not None and r["owner_idle_days"] >= args.inactive_days
               and r["owner_share"] >= 100.0 * args.min_share]
    dir_rows = []
    for folder in sorted(dirs):
        counts = dirs[folder]
        owner, share = top_owner(counts)
        dir_rows.append({
            "directory": folder,
            "files": sum(1 for p in files if top_dir(p) == folder),
            "commits": sum(counts.values()),
            "authors": len(counts),
            "bus_factor": bus_factor(counts),
            "main_owner": people.display(owner),
            "owner_share": round(100.0 * share, 1),
            "basis": "commits",
        })
    dir_rows.sort(key=lambda r: (-r["commits"], r["directory"]))
    blamed_total = {}
    for counts in blamed.values():
        for key, value in counts.items():
            blamed_total[key] = blamed_total.get(key, 0) + value
    owner, share = top_owner(repo_counts)
    summary = {
        "commits_scanned": scanned,
        "bot_commits_excluded": bot_commits,
        "bot_lines_excluded": bot_lines,
        "authors": len(repo_counts),
        "bus_factor_commits": bus_factor(repo_counts),
        "bus_factor_blamed_lines": bus_factor(blamed_total) if blamed_total else None,
        "blamed_files": len(blamed),
        "blame_timeouts": timeouts,
        "main_author": people.display(owner) if owner else None,
        "main_author_share": round(100.0 * share, 1),
    }
    return rows, dir_rows, at_risk, summary


def render_markdown(report):
    s = report["summary"]
    out = ["# Ownership: " + report["repo"], ""]
    window = report["window"]
    out.append("- Window: " + ("all history" if not window["since"] else "since " + window["since"]))
    out.append("- As of: {} (a person is inactive after {} days without a commit)".format(
        report["as_of"], report["inactive_days"]))
    out.append("- Commits scanned: {} ({} bot commits excluded); authors after merging aliases: {}".format(
        s["commits_scanned"], s["bot_commits_excluded"], s["authors"]))
    out.append("- Repository bus factor by commits: {}".format(s["bus_factor_commits"]))
    if s["bus_factor_blamed_lines"] is not None:
        out.append("- Bus factor by surviving lines in the {} blamed files: {}".format(
            s["blamed_files"], s["bus_factor_blamed_lines"]))
    if s["blame_timeouts"]:
        out.append("- Blame timed out or failed, commit share used instead: " + ", ".join(
            "`{}`".format(p) for p in s["blame_timeouts"]))
    out.append("")
    out.append("## Directories (share of commits)")
    out.append("")
    out.append("| Directory | Files | Commits | Authors | Bus factor | Main owner | Share |")
    out.append("|---|--:|--:|--:|--:|---|--:|")
    for r in report["directories"]:
        out.append("| `{directory}` | {files} | {commits} | {authors} | {bus_factor} | {main_owner} "
                   "| {owner_share}% |".format(**r))
    out.append("")
    out.append("## Most-changed files")
    out.append("")
    out.append("| File | Commits | Authors | Bus factor | Main owner | Share | Basis | Owner last commit |")
    out.append("|---|--:|--:|--:|---|--:|---|---|")
    for r in report["files"]:
        out.append("| `{file}` | {commits} | {authors} | {bus_factor} | {main_owner} | {owner_share}% "
                   "| {basis} | {owner_last_commit} |".format(**r))
    out.append("")
    out.append("## Knowledge at risk")
    out.append("")
    if report["knowledge_at_risk"]:
        out.append("| File | Main owner | Share | Owner last commit | Idle days | Commits | Basis |")
        out.append("|---|---|--:|---|--:|--:|---|")
        for r in report["knowledge_at_risk"]:
            out.append("| `{file}` | {main_owner} | {owner_share}% | {owner_last_commit} | {owner_idle_days} "
                       "| {commits} | {basis} |".format(**r))
    else:
        out.append("No file has a main owner who has been idle for {} days or more.".format(
            report["inactive_days"]))
    out.append("")
    out.append("Basis `blame` counts lines that survive at HEAD; `commits` counts commits in the window. "
               "Both measure who committed, not who understands the code. Do not use this to rank people.")
    out.append("")
    return "\n".join(out)


def parse_day(text):
    try:
        day = datetime.strptime(text, "%Y-%m-%d")
    except ValueError:
        return None
    return day.replace(hour=23, minute=59, second=59, tzinfo=timezone.utc).timestamp()


def parse_args(argv):
    parser = argparse.ArgumentParser(
        prog="owners.py", description="Ownership, bus factor and knowledge at risk from git history.")
    parser.add_argument("repo", nargs="?", default=".", help="path inside a git repository (default .)")
    parser.add_argument("--since", help='start of the window, anything git understands ("24 months ago")')
    parser.add_argument("--as-of", metavar="YYYY-MM-DD",
                        help="treat this day as today (also ignores later commits); default: now")
    parser.add_argument("--path", action="append", default=[], metavar="PATHSPEC",
                        help="limit history to this path (repeatable)")
    parser.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                        help="skip files matching this glob or dir/ (repeatable, added to the defaults)")
    parser.add_argument("--no-default-excludes", action="store_true",
                        help="do not skip lockfiles, vendored, generated, minified and binary files")
    parser.add_argument("--top", type=int, default=15, help="files to blame and to list (default 15)")
    parser.add_argument("--file", action="append", default=[], metavar="PATH",
                        help="blame exactly these files (repeatable) instead of the most-changed ones")
    parser.add_argument("--fast", action="store_true", help="skip git blame; share commits only")
    parser.add_argument("--blame-timeout", type=float, default=20.0,
                        help="seconds allowed per blamed file before falling back to commits (default 20)")
    parser.add_argument("--ignore-revs", metavar="FILE",
                        help="revisions blame should skip (default: .git-blame-ignore-revs if present)")
    parser.add_argument("--inactive-days", type=int, default=180,
                        help="days without any commit before a person counts as inactive (default 180)")
    parser.add_argument("--min-share", type=float, default=0.5,
                        help="owner share (0 to 1) a file needs to count as at risk (default 0.5)")
    parser.add_argument("--merge-email-domain", action="append", default=[], metavar="DOMAIN",
                        help="treat the same local part at these domains as one person (repeatable)")
    parser.add_argument("--exclude-author", action="append", default=[], metavar="REGEX",
                        help="also drop authors whose 'Name <email>' matches this regex (repeatable)")
    parser.add_argument("--include-bots", action="store_true", help="do not drop bot identities")
    parser.add_argument("--label", help="name to print instead of the repository folder name")
    parser.add_argument("--fail-at-risk", type=int, metavar="N",
                        help="exit 1 if at least N files are knowledge at risk")
    parser.add_argument("--json", action="store_true", help="print JSON instead of markdown")
    parser.add_argument("-o", "--output", help="write the report to this file instead of stdout")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    setup_output()
    args = parse_args(argv)
    if args.top < 1 or args.inactive_days < 0 or not 0 <= args.min_share <= 1 or args.blame_timeout <= 0:
        print("owners: --top must be at least 1, --inactive-days at least 0, --min-share between 0 and 1 "
              "and --blame-timeout above 0", file=sys.stderr)
        return 2
    until = None
    as_of_ts = time.time()
    if args.as_of:
        as_of_ts = parse_day(args.as_of)
        if as_of_ts is None:
            print("owners: --as-of must look like 2026-11-01", file=sys.stderr)
            return 2
        until = args.as_of + " 23:59:59 +0000"
    try:
        bot_res = [] if args.include_bots else [re.compile(p, re.IGNORECASE) for p in BOT_PATTERNS]
        bot_res += [re.compile(p, re.IGNORECASE) for p in args.exclude_author]
    except re.error as exc:
        print("owners: bad --exclude-author regex: " + str(exc), file=sys.stderr)
        return 2
    people = People(args.merge_email_domain, bot_res)
    try:
        repo = open_repo(args.repo)
        patterns = exclude_patterns(args.exclude, not args.no_default_excludes)
        rows, dir_rows, at_risk, summary = analyse(repo, args, people, patterns, as_of_ts, until)
    except GitError as exc:
        print("owners: " + str(exc), file=sys.stderr)
        return 2
    report = {
        "repo": args.label or os.path.basename(repo.rstrip("/\\")) or "repo",
        "window": {"since": args.since},
        "as_of": args.as_of or fmt_day(as_of_ts),
        "inactive_days": args.inactive_days,
        "summary": summary,
        "directories": dir_rows[:30],
        "files": rows[:args.top],
        "knowledge_at_risk": at_risk[:args.top],
        "knowledge_at_risk_total": len(at_risk),
        "limits": [
            "Shares measure commits or surviving lines, not understanding or skill.",
            "Squash merges credit the merger; mass reformat commits and vendor drops can capture lines "
            "(use .git-blame-ignore-revs).",
            "Different emails for one person are merged only through .mailmap and --merge-email-domain.",
        ],
    }
    text = json.dumps(report, indent=2, sort_keys=True) + "\n" if args.json else render_markdown(report)
    if args.output:
        with open(args.output, "w", newline="\n", encoding="utf-8") as handle:
            handle.write(text)
    else:
        sys.stdout.write(text)
    if args.fail_at_risk is not None and len(at_risk) >= args.fail_at_risk:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
