SEP_FIELD = "\x1f"
SEP_COMMIT = "\x01"
LOG_FORMAT = SEP_COMMIT + SEP_FIELD.join(["%H", "%aN", "%aE", "%at", "%s"])


class GitError(Exception):
    """A git problem the user can act on (not a repo, no commits, git missing)."""


class Change(object):
    """One file touched by a commit. `old` is the previous path when git saw a rename."""

    __slots__ = ("path", "added", "deleted", "old", "binary")

    def __init__(self, path, added, deleted, old=None, binary=False):
        self.path = path
        self.added = added
        self.deleted = deleted
        self.old = old
        self.binary = binary


class Commit(object):
    __slots__ = ("sha", "name", "email", "ts", "subject", "changes")

    def __init__(self, sha, name, email, ts, subject):
        self.sha = sha
        self.name = name
        self.email = email
        self.ts = ts
        self.subject = subject
        self.changes = []


def git_env():
    env = dict(os.environ)
    env["LC_ALL"] = "C"
    env["GIT_PAGER"] = "cat"
    env["GIT_TERMINAL_PROMPT"] = "0"
    return env


def git_args(repo, args):
    return ["git", "-c", "core.quotepath=off", "-c", "core.pager=cat", "-C", repo] + list(args)


def git_text(repo, args):
    """Run git and return stdout as text. Raises GitError when git is missing or fails."""
    try:
        proc = subprocess.run(git_args(repo, args), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              env=git_env())
    except OSError as exc:
        raise GitError("cannot run git: " + str(exc))
    if proc.returncode != 0:
        message = proc.stderr.decode("utf-8", "replace").strip().split("\n")[-1]
        raise GitError("git " + " ".join(args[:2]) + " failed: " + message)
    return proc.stdout.decode("utf-8", "replace")


def open_repo(path):
    """Return the top-level directory of the repository at `path`, or raise GitError."""
    if not os.path.isdir(path):
        raise GitError("not a directory: " + path)
    top = git_text(path, ["rev-parse", "--show-toplevel"]).strip()
    try:
        git_text(top, ["rev-parse", "--verify", "-q", "HEAD"])
    except GitError:
        raise GitError("repository has no commits yet: " + path)
    return top


def stream_nul(args_list, repo, chunk=65536):
    """Run git and yield its NUL-separated output tokens as bytes, one at a time."""
    errfile = tempfile.TemporaryFile()
    try:
        proc = subprocess.Popen(git_args(repo, args_list), stdout=subprocess.PIPE, stderr=errfile,
                                env=git_env())
    except OSError as exc:
        errfile.close()
        raise GitError("cannot run git: " + str(exc))
    try:
        rest = b""
        while True:
            data = proc.stdout.read(chunk)
            if not data:
                break
            rest += data
            parts = rest.split(b"\0")
            rest = parts.pop()
            for part in parts:
                yield part
        if rest:
            yield rest
        proc.stdout.close()
        code = proc.wait()
        if code != 0:
            errfile.seek(0)
            message = errfile.read().decode("utf-8", "replace").strip().split("\n")[-1]
            raise GitError("git log failed: " + message)
    finally:
        if proc.poll() is None:
            proc.kill()
            proc.wait()
        errfile.close()


def iter_commits(repo, since=None, until=None, pathspecs=None, numstat=True):
    """Stream commits (newest first, merges skipped) with their numstat changes.

    Parses `git log -z --numstat -M` records: a header token that starts with SEP_COMMIT, then
    `added<TAB>deleted<TAB>path` tokens; a rename is `added<TAB>deleted<TAB>` followed by the old
    and the new path as two more tokens. Paths never need unquoting because of -z.
    """
    args = ["log", "--no-merges", "-z", "--format=" + LOG_FORMAT]
    if numstat:
        args += ["--numstat", "-M"]
    if since:
        args.append("--since=" + since)
    if until:
        args.append("--until=" + until)
    if pathspecs:
        args += ["--"] + list(pathspecs)
    current = None
    rename_tokens = []
    for raw in stream_nul(args, repo):
        token = raw.decode("utf-8", "replace")
        if rename_tokens:
            rename_tokens.append(token)
            if len(rename_tokens) == 3:
                stats, old, new = rename_tokens
                rename_tokens = []
                add, dele, binary = _numbers(stats)
                if current is not None:
                    current.changes.append(Change(new, add, dele, old=old, binary=binary))
            continue
        token = token.lstrip("\n")
        if token.startswith(SEP_COMMIT):
            if current is not None:
                yield current
            fields = token[1:].split(SEP_FIELD, 4)
            if len(fields) < 5:
                fields += [""] * (5 - len(fields))
            try:
                ts = int(fields[3])
            except ValueError:
                ts = 0
            current = Commit(fields[0], fields[1], fields[2].lower(), ts, fields[4])
            continue
        if not token or current is None:
            continue
        pieces = token.split("\t", 2)
        if len(pieces) != 3:
            continue
        if pieces[2] == "":
            rename_tokens = [pieces[0] + "\t" + pieces[1]]
            continue
        add, dele, binary = _numbers(pieces[0] + "\t" + pieces[1])
        current.changes.append(Change(pieces[2], add, dele, binary=binary))
    if current is not None:
        yield current


def _numbers(text):
    left, _, right = text.partition("\t")
    if left == "-" or right == "-":
        return 0, 0, True
    try:
        return int(left), int(right), False
    except ValueError:
        return 0, 0, False


class RenameMap(object):
    """Follow renames while reading history newest first.

    When a commit renames old -> new, every older commit that touches `old` belongs to the file
    that is now called `new` (or whatever `new` became later). Limits: git only detects renames
    above its similarity threshold (50 percent by default), so a heavily edited move looks like a
    delete plus an add, and a --path filter can hide one side of a rename.
    """

    def __init__(self):
        self.alias = {}

    def resolve(self, path):
        seen = 0
        while path in self.alias and seen < 50:
            path = self.alias[path]
            seen += 1
        return path

    def note(self, change):
        if change.old and change.old != change.path:
            self.alias[change.old] = self.resolve(change.path)


def is_pure_rename(change):
    return bool(change.old) and change.added == 0 and change.deleted == 0


def pattern_matches(path, pattern):
    """Glob match on the whole path or the file name; a trailing slash means a directory."""
    if pattern.endswith("/"):
        folder = pattern
        return path.startswith(folder) or ("/" + folder) in ("/" + path)
    base = path.rsplit("/", 1)[-1]
    return fnmatch.fnmatchcase(path, pattern) or fnmatch.fnmatchcase(base, pattern)


def is_excluded(path, patterns):
    return any(pattern_matches(path, p) for p in patterns)


def exclude_patterns(extra, use_defaults=True):
    return (list(DEFAULT_EXCLUDES) if use_defaults else []) + list(extra or [])


def tracked_files(repo):
    """Set of paths in HEAD (what exists now)."""
    out = git_text(repo, ["ls-files", "-z"])
    return set(p for p in out.split("\0") if p)


def read_bytes(repo, path, limit=4 * 1024 * 1024):
    """Read a working-tree file (up to `limit` bytes), or None when it is missing."""
    full = os.path.join(repo, *path.split("/"))
    try:
        with open(full, "rb") as handle:
            return handle.read(limit)
    except OSError:
        return None


def looks_binary(data):
    return b"\0" in data[:8192]


def setup_output():
    """Print UTF-8 whatever the console code page is (file names can be non-ASCII)."""
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            try:
                reconfigure(encoding="utf-8", errors="replace")
            except (OSError, ValueError):
                pass


def top_dir(path):
    return path.split("/", 1)[0] if "/" in path else "."
